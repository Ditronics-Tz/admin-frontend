export function promoText(
  locale: AppLocale,
  message: string,
  values: Record<string, string | number> = {}
) {
  return (locale === 'sw' ? sw[message] || message : message).replace(
    /\{(\w+)\}/g,
    (_, key: string) => String(values[key] ?? `{${key}}`)
  )
}
export function usePromoText() {
  const locale = useUiStore((s) => s.locale)
  return (message: string, values?: Record<string, string | number>) =>
    promoText(locale, message, values)
}
